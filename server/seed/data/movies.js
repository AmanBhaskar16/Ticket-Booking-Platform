export const bannerFromTrailer = (trailerUrl, frame) => {
    const id = trailerUrl?.match(/(?:v=|youtu\.be\/|embed\/)([\w-]{11})/)?.[1];
    return id && frame ? `https://i.ytimg.com/vi/${id}/maxres${frame}.jpg` : "";
};
