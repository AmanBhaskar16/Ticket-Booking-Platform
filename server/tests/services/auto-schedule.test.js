import { describe, it, expect, beforeAll, afterAll, beforeEach, vi } from "vitest";
import mongoose from "mongoose";

import { connectTestDb, disconnectTestDb, clearTestDb } from "../setup/testDb.js";

vi.mock("../../services/email.service.js", () => ({
    sendShowReminderEmail: vi.fn().mockResolvedValue(undefined),
}));

const {
    scheduleUpcomingShowsService, pruneOldShowsService, releaseDueMoviesService,
} = await import("../../services/autoSchedule.service.js");
const { THEATRES, buildScreens } = await import("../../seed/data/theatres.js");
const { assertValidLayout } = await import("../../utils/seatLayout.js");
const Theatre = (await import("../../models/theatre.model.js")).default;
const Show    = (await import("../../models/show.model.js")).default;
const Movie   = (await import("../../models/movie.model.js")).default;
const Booking = (await import("../../models/bookings.model.js")).default;
await import("../../models/user.model.js");

const DAY = 24 * 3_600_000;
// Sunday 1 Nov 2026, 10:00 AM IST
const NOW = new Date("2026-11-01T04:30:00Z");
const istHourMin = (d) => new Date(d.getTime() + 330 * 60_000).toISOString().slice(11, 16);
const istDay = (d) => new Date(d.getTime() + 330 * 60_000).toISOString().slice(0, 10);

const movie = (over = {}) => Movie.create({
    name: "Test Movie", description: "d", casts: ["A"], trailerUrl: "https://x.test/t",
    languages: ["Hindi", "English"], releaseDate: new Date("2026-10-01"), duration: 150,
    posterUrl: "p", genre: ["Action"], director: "D", releaseStatus: "RELEASED", ...over,
});

const theatre = (movies, over = {}) => Theatre.create({
    name: "Test Cinema", city: "Delhi", state: "Delhi", pincode: 110001, address: "Somewhere 1",
    owner: new mongoose.Types.ObjectId(), movies: movies.map((m) => m._id), totalScreens: 2,
    screens: buildScreens(["imax", "standard"], 1), ...over,
});

describe("auto-scheduler", () => {
    beforeAll(connectTestDb);
    afterAll(disconnectTestDb);
    beforeEach(clearTestDb);

    it("fills a rolling 8-day window on every screen, within cinema hours", async () => {
        const m = await movie();
        const t = await theatre([m]);

        const created = await scheduleUpcomingShowsService(NOW);
        const shows = await Show.find({ theatreId: t._id }).sort({ showTime: 1 });

        expect(created).toBe(shows.length);
        expect(new Set(shows.map((s) => istDay(s.showTime))).size).toBe(8);
        expect(new Set(shows.map((s) => s.screen))).toEqual(new Set(["IMAX Hall", "Audi 1"]));
        for (const s of shows) {
            expect(s.autoGenerated).toBe(true);
            expect(s.showTime.getTime()).toBeGreaterThan(NOW.getTime() + 29 * 60_000);
            expect(istHourMin(s.showTime) >= "09:00" && istHourMin(s.showTime) <= "23:15").toBe(true);
            expect(s.seatLayout).toBeTruthy();
            expect(s.noOfSeats).toBe(s.seatLayout.rows.length * s.seatLayout.cols);
        }
        expect(shows.filter((s) => s.screen === "IMAX Hall").every((s) => s.format === "IMAX")).toBe(true);
    });

    it("never overlaps shows on one screen", async () => {
        const m = await movie({ duration: 170 });
        await theatre([m]);
        await scheduleUpcomingShowsService(NOW);
        const shows = await Show.find({ screen: "Audi 1" }).sort({ showTime: 1 });
        for (let i = 1; i < shows.length; i++) {
            if (istDay(shows[i].showTime) !== istDay(shows[i - 1].showTime)) continue;
            expect(shows[i].showTime - shows[i - 1].showTime).toBeGreaterThanOrEqual((170 + 20) * 60_000);
        }
    });

    it("is idempotent and leaves hand-scheduled screen-days alone", async () => {
        const m = await movie();
        const t = await theatre([m]);
        const manual = await Show.create({
            theatreId: t._id, movieId: m._id, screen: "Audi 1", noOfSeats: 80, price: 200,
            showTime: new Date(NOW.getTime() + 2 * DAY),
        });

        await scheduleUpcomingShowsService(NOW);
        const before = await Show.countDocuments();
        expect(await scheduleUpcomingShowsService(NOW)).toBe(0);
        expect(await Show.countDocuments()).toBe(before);

        const sameDay = await Show.find({ screen: "Audi 1", _id: { $ne: manual._id } });
        expect(sameDay.some((s) => istDay(s.showTime) === istDay(manual.showTime))).toBe(false);
    });

    it("skips theatres with autoSchedule off and movies not yet released", async () => {
        const out = await movie({ name: "Out now" });
        const soon = await movie({ name: "Soon", releaseStatus: "COMING_SOON", releaseDate: new Date("2026-11-05") });
        await theatre([out], { autoSchedule: false });
        await theatre([out, soon], { name: "Other Cinema" });

        await scheduleUpcomingShowsService(NOW);
        const soonShows = await Show.find({ movieId: soon._id });
        expect(soonShows.length).toBeGreaterThan(0);
        expect(soonShows.every((s) => istDay(s.showTime) >= "2026-11-05")).toBe(true);
        expect(await Show.distinct("theatreId")).toHaveLength(1);
    });

    it("releases coming-soon movies on their release date", async () => {
        const soon = await movie({ releaseStatus: "COMING_SOON", releaseDate: new Date("2026-10-31") });
        const later = await movie({ name: "Later", releaseStatus: "COMING_SOON", releaseDate: new Date("2026-12-18") });
        expect(await releaseDueMoviesService(NOW)).toBe(1);
        expect((await Movie.findById(soon._id)).releaseStatus).toBe("RELEASED");
        expect((await Movie.findById(later._id)).releaseStatus).toBe("COMING_SOON");
    });

    it("prunes only old, unbooked, auto-created shows", async () => {
        const m = await movie();
        const t = await theatre([m]);
        const base = { theatreId: t._id, movieId: m._id, screen: "Audi 1", noOfSeats: 80, price: 200 };
        const old = new Date(NOW.getTime() - 3 * DAY);
        const [stale, booked, withBooking, manual, recent] = await Show.create([
            { ...base, showTime: old, autoGenerated: true },
            { ...base, showTime: old, autoGenerated: true, bookedSeats: ["A1"] },
            { ...base, showTime: old, autoGenerated: true },
            { ...base, showTime: old },
            { ...base, showTime: new Date(NOW.getTime() - DAY), autoGenerated: true },
        ]);
        await Booking.create({ showId: withBooking._id, userId: new mongoose.Types.ObjectId(), seats: ["B1"], totalAmount: 200, status: "CANCELLED" });

        expect(await pruneOldShowsService(NOW)).toBe(1);
        const left = (await Show.find().select("_id")).map((s) => s._id.toString());
        expect(left).not.toContain(stale._id.toString());
        for (const keep of [booked, withBooking, manual, recent]) expect(left).toContain(keep._id.toString());
    });

    it("seed cinema layouts are valid", () => {
        for (const spec of THEATRES) {
            for (const screen of buildScreens(spec.screens, spec.factor)) expect(() => assertValidLayout(screen.layout)).not.toThrow();
        }
    });
});
